import { writeFile } from 'fs/promises';
import { By, until } from 'selenium-webdriver';
import { driver, markers, test } from 'thousandeyes';

const IMPLICIT_TIMEOUT_MS = 5 * 1000;
const UPLOAD_PATH = '/tmp/thousandeyes-upload.txt';
const UPLOAD_BODY = 'Generated by ThousandEyes transaction test.\n';
const EXPECTED_SUCCESS_TEXT = 'uploaded';
const FILE_INPUT_SELECTOR = By.css('input[type="file"]');
const SUBMIT_SELECTOR = By.css('button[type="submit"]');
const SUCCESS_SELECTOR = By.css('[data-testid="upload-success"]');

runScript();

async function runScript() {
  await configureDriver();

  const settings = test.getSettings();
  const targetUrl = settings.url;

  await writeFile(UPLOAD_PATH, UPLOAD_BODY, 'utf8');
  await driver.get(targetUrl);

  markers.start('Upload');
  const input = await waitForVisible(FILE_INPUT_SELECTOR, 15 * 1000);
  await input.sendKeys(UPLOAD_PATH);

  const submit = await waitForVisible(SUBMIT_SELECTOR, 10 * 1000);
  await submit.click();

  const success = await waitForVisible(SUCCESS_SELECTOR, 20 * 1000);
  markers.stop('Upload');

  const successText = await success.getText();
  if (!successText.toLowerCase().includes(EXPECTED_SUCCESS_TEXT.toLowerCase())) {
    throw new Error(`Expected upload confirmation was not present. textLength=${successText.length}`);
  }

  await driver.takeScreenshot();
}

async function configureDriver() {
  await driver.manage().setTimeouts({
    implicit: IMPLICIT_TIMEOUT_MS,
  });
}

async function waitForVisible(locator, timeoutMs) {
  const element = await driver.wait(until.elementLocated(locator), timeoutMs);
  await driver.wait(until.elementIsVisible(element), timeoutMs);
  return element;
}
